var (
	publicOnce sync.Once
	publicLib  Library
	publicErr  error
)

// Public returns the shipped generic layer. It panics if the binary's own data is
// invalid: that is a build-time bug, and TestPublicLibraryIsWellFormed catches it
// before release rather than letting an operator discover it.
func Public() Library {
	publicOnce.Do(func() {
		publicLib, publicErr = New(generic...)
		if publicErr != nil {
			panic("pattern: the shipped library is invalid: " + publicErr.Error())
		}
	})
	return publicLib
}
