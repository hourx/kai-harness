// Package report renders a submission draft in a platform's own field set.
//
// Bug-bounty report forms have fixed fields, and a finding that is real still
// gets closed if the wrong field is empty. This package does exactly one thing:
// lay out the platform's form, prefill what the tool knows (target, class,
// evidence, hashes), and leave the judgement blank for the operator to write.
//
// kai drafts. kai never submits.
package report

import (
	"errors"
	"fmt"
	"sort"
	"strings"

	"github.com/hourx/kai-harness/pkg/evidence"
)

// KV is one labelled extra line, kept ordered so output is reproducible.
type KV struct {
	Label string `json:"label"`
	Value string `json:"value"`
}

// Input is everything a draft can be built from.
type Input struct {
	Program   string
	Platform  string
	Title     string
	Severity  string
	Target    string
	Class     string
	FindingID string
	Status    string
	Note      string
	ScopeLine string
	// ScopeVerdict is "in", "out" or "" (unknown). Only the gate may set it.
	ScopeVerdict string
	Channel      string
	Evidence     []evidence.Item
	Extra        []KV
}

// Platforms lists the supported field sets, in the order the CLI prints them.
var Platforms = []string{"hackerone", "bugcrowd", "yandex"}

var blank = "______"

// Valid reports whether the platform has a field set.
func Valid(platform string) bool {
	for _, p := range Platforms {
		if p == platform {
			return true
		}
	}
	return false
}

// Render builds the draft. An unknown platform is an error, never a guess: the
// wrong form wastes a triager's time and buries the finding.
func Render(in Input) (string, error) {
	if !Valid(in.Platform) {
		return "", fmt.Errorf("unknown platform %q — one of: %s", in.Platform, strings.Join(Platforms, ", "))
	}
	if strings.TrimSpace(in.Title) == "" && strings.TrimSpace(in.Target) == "" {
		return "", errors.New("draft needs --title or --target: a report with no subject cannot be triaged")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Submission draft — %s (%s)\n\n", in.Program, in.Platform)
	b.WriteString("Generated by `kai report-draft`. Every blank is the operator's to fill: kai holds no\n")
	b.WriteString("opinion on impact and does not submit. Review the scope line and the evidence list\n")
	b.WriteString("before copying anything into a form.\n\n")
	if len(in.Evidence) == 0 {
		b.WriteString("> **No evidence attached.** A report without a reproduction artifact is a guess.\n")
		b.WriteString("> Capture one first: `kai evidence " + in.Program + " add --kind response --host H --method GET --path /p --file raw.txt`.\n\n")
	}
	if in.ScopeVerdict == "out" {
		b.WriteString("> **The scope gate returned OUT for this host.** Submitting this report risks the\n")
		b.WriteString("> program relationship and the payout. Re-check the policy before going further.\n\n")
	}

	b.WriteString("## Scope check\n\n")
	fmt.Fprintf(&b, "- target: `%s`\n", orDash(in.Target))
	if in.ScopeLine != "" {
		fmt.Fprintf(&b, "- scope: %s\n", in.ScopeLine)
	} else {
		fmt.Fprintf(&b, "- scope: run `kai scope %s <host>` and paste the result here\n", in.Program)
	}
	if in.Channel != "" {
		fmt.Fprintf(&b, "- submission channel: %s\n", in.Channel)
	}
	b.WriteString("\n")

	switch in.Platform {
	case "hackerone":
		writeHackerOne(&b, in)
	case "bugcrowd":
		writeBugcrowd(&b, in)
	case "yandex":
		writeYandex(&b, in)
	}

	if len(in.Evidence) > 0 {
		b.WriteString("## Evidence (generated)\n\n")
		b.WriteString(evidence.Markdown(sorted(in.Evidence)))
		b.WriteString("\n")
	}

	if len(in.Extra) > 0 {
		b.WriteString("## Extra\n\n")
		for _, kv := range in.Extra {
			fmt.Fprintf(&b, "- %s: %s\n", kv.Label, kv.Value)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Checklist before submitting\n\n")
	b.WriteString("- [ ] scope gate returned IN for the target host\n")
	b.WriteString("- [ ] steps reproduce from a clean session, three times\n")
	b.WriteString("- [ ] impact names the data or capability an attacker gains\n")
	b.WriteString("- [ ] evidence hash in this file matches the bytes attached\n")
	b.WriteString("- [ ] no out-of-scope asset was touched while proving it\n")
	return b.String(), nil
}

func writeHackerOne(b *strings.Builder, in Input) {
	fmt.Fprintf(b, "## Title\n\n%s\n\n", orBlank(in.Title))
	b.WriteString("## Severity\n\n")
	fmt.Fprintf(b, "%s\n\n", orBlank(in.Severity))
	fmt.Fprintf(b, "_basis: %s_\n\n", orBlank(in.Note))
	b.WriteString("## Weakness (CWE)\n\n")
	fmt.Fprintf(b, "%s\n\n", orBlank(in.Class))
	b.WriteString("## Asset\n\n")
	fmt.Fprintf(b, "%s\n\n", orBlank(in.Target))
	b.WriteString("## Vulnerability Information\n\n")
	b.WriteString("### Description\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("### Impact\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("### Steps To Reproduce\n\n")
	fmt.Fprintf(b, "1. %s\n2. %s\n3. %s\n\n", blank, blank, blank)
	b.WriteString("### Supporting Material / References\n\n")
	fmt.Fprintf(b, "- %s\n\n", blank)
}

func writeBugcrowd(b *strings.Builder, in Input) {
	fmt.Fprintf(b, "## Summary\n\n%s\n\n", orBlank(in.Title))
	fmt.Fprintf(b, "## Target\n\n%s\n\n", orBlank(in.Target))
	fmt.Fprintf(b, "## Severity\n\n%s\n\n", orBlank(in.Severity))
	b.WriteString("## Description\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("## Steps to Reproduce\n\n")
	fmt.Fprintf(b, "1. %s\n2. %s\n3. %s\n\n", blank, blank, blank)
	b.WriteString("## Impact\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("## References\n\n")
	fmt.Fprintf(b, "- class: %s\n- finding: %s\n- %s\n\n", orBlank(in.Class), orDash(in.FindingID), blank)
}

func writeYandex(b *strings.Builder, in Input) {
	b.WriteString("## Security impact (pick one)\n\n")
	b.WriteString("- [ ] Yes, it is a vulnerability\n- [ ] No, it is not a vulnerability\n\n")
	fmt.Fprintf(b, "## Subject\n\n%s\n\n", orBlank(in.Title))
	b.WriteString("## Step-by-step instructions to reproduce\n\n")
	fmt.Fprintf(b, "1. %s\n2. %s\n3. %s\n\n", blank, blank, blank)
	b.WriteString("## Result\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("## Expected result and recommendations\n\n")
	fmt.Fprintf(b, "%s\n\n", blank)
	b.WriteString("## Category\n\n")
	b.WriteString("- [ ] Web & other\n- [ ] Alice & Smart Device\n- [ ] Mobile\n\n")
	b.WriteString("## Vulnerability type\n\n")
	fmt.Fprintf(b, "%s\n\n", orBlank(in.Class))
	b.WriteString("_picklist in the form: Account takeover, Authentication Issue, Binary, Bruteforce, Business Logic, XSS, CSRF, DoS, IDOR/Broken ACL, Information Disclosure, Injections, Open Redirect, Path Traversal, Privilege Escalation, Race Condition, RCE, Security Misconfiguration, Sensitive Info in Source Code, Vulnerable Components, XXE, Others_\n\n")
}

func sorted(in []evidence.Item) []evidence.Item {
	out := append([]evidence.Item{}, in...)
	evidence.Sort(out)
	return out
}

func orBlank(s string) string {
	if strings.TrimSpace(s) == "" {
		return blank
	}
	return s
}

func orDash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return s
}

// SortKV orders extra fields so renders stay reproducible.
func SortKV(in []KV) []KV {
	out := append([]KV{}, in...)
	sort.SliceStable(out, func(i, j int) bool { return out[i].Label < out[j].Label })
	return out
}
