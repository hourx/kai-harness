package program

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ValidationGate renders the Skeptic checklist with the answers kai already
// knows. It does not validate anything: every conclusion is left blank for the
// agent, and every prefill states what file it came from. A missing file is
// "unknown", never permission.
func ValidationGate(pDir string) (string, error) {
	name := filepath.Base(pDir)
	scope := readGateFile(filepath.Join(pDir, "scope.txt"))
	outScope := readGateFile(filepath.Join(pDir, "out-of-scope.txt"))
	bound := readGateFile(filepath.Join(pDir, "boundaries.md"))
	dupes := readGateFile(filepath.Join(pDir, "findings", "dupes.md"))
	lessons := readGateFile(filepath.Join(pDir, "findings", "lessons.md"))

	var in Intake
	if b, err := os.ReadFile(filepath.Join(pDir, "intake.json")); err == nil {
		_ = json.Unmarshal(b, &in)
	}
	submission := in.Boundaries.SubmissionChannel
	contacts := strings.Join(in.Boundaries.SubmissionContact, ", ")
	if contacts == "" {
		contacts = "no public contact recorded"
	}
	// Older intake.json files only carry "email-or-contact". A single published
	// address plus that marker is enough to surface a candidate channel — still
	// flagged for verification, never presented as fact.
	if submission == "" || strings.HasPrefix(submission, "email-or-contact") || strings.EqualFold(submission, "unknown") {
		if len(in.Boundaries.SubmissionContact) == 1 {
			submission = "email:" + in.Boundaries.SubmissionContact[0] + " (from the policy contact — verify)"
		} else if submission == "" {
			submission = "unknown — not found on the program page"
		}
	}

	queue := 0
	if b, err := os.ReadFile(filepath.Join(pDir, "next.json")); err == nil {
		var plan struct {
			Items []struct {
				Target string `json:"target"`
			} `json:"items"`
		}
		if json.Unmarshal(b, &plan) == nil {
			queue = len(plan.Items)
		}
	}

	ledger := "no ledger yet"
	if b, err := os.ReadFile(filepath.Join(pDir, "findings", "ledger.json")); err == nil {
		var doc struct {
			Findings []json.RawMessage `json:"findings"`
		}
		if json.Unmarshal(b, &doc) == nil {
			ledger = fmt.Sprintf("%d entries in findings/ledger.json", len(doc.Findings))
		} else {
			var arr []json.RawMessage
			if json.Unmarshal(b, &arr) == nil {
				ledger = fmt.Sprintf("%d entries in findings/ledger.json", len(arr))
			} else if len(strings.TrimSpace(string(b))) > 2 {
				ledger = "findings/ledger.json present (unrecognised format)"
			}
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "# Validation gate — %s\n\n", name)
	out.WriteString("Generated by `kai export`. Every prefill below comes from a file; ")
	out.WriteString("every conclusion is still blank and must be filled in by the Skeptic.\n\n")

	fmt.Fprintf(&out, "1. **Scope**: does the target pass the rules?\n   - scope.txt: %s\n   - out-of-scope.txt: %s\n   - ANSWER: ______\n\n",
		gateSummary(scope, "no scope.txt — do not guess"),
		gateSummary(outScope, "no out-of-scope.txt — treat as unknown"))

	fmt.Fprintf(&out, "2. **Program rules**: is the impact class accepted?\n   - boundaries.md: %s\n   - ANSWER: ______\n\n",
		gateSummary(bound, "no boundaries.md — run `kai boundaries "+name+"`"))

	fmt.Fprintf(&out, "3. **Evidence**: is there a PoC / reproducible proof?\n   - %s\n   - kai queue: %d hypotheses\n   - ANSWER: ______\n\n",
		ledger, queue)

	fmt.Fprintf(&out, "4. **Duplicate**: has this been reported before?\n   - dupes.md: %s\n   - lessons.md: %s\n   - ANSWER: ______\n\n",
		gateSummary(dupes, "no duplicate notes"),
		gateSummary(lessons, "no lessons recorded"))

	contactLine := contacts + " (a contact, not a channel)"
	if strings.HasPrefix(submission, "email:") && len(in.Boundaries.SubmissionContact) == 1 &&
		strings.Contains(submission, in.Boundaries.SubmissionContact[0]) {
		contactLine = "same as the channel above — not an extra contact"
	}
	fmt.Fprintf(&out, "5. **Submission channel**: is this the official channel?\n   - channel: %s\n   - contact: %s\n   - ANSWER: ______\n\n",
		submission, contactLine)

	fmt.Fprintf(&out, "6. **Attacker & victim**: who needs access, and who is affected?\n   - ANSWER: ______\n\n")
	fmt.Fprintf(&out, "7. **Reproduce 3x**: can it be repeated from scratch with written steps?\n   - ANSWER: ______\n")

	return out.String(), nil
}

func readGateFile(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(b))
}

func gateSummary(text, empty string) string {
	if strings.TrimSpace(text) == "" {
		return empty
	}
	lines := strings.Split(strings.TrimSpace(text), "\n")
	if len(lines) > 3 {
		lines = lines[:3]
	}
	return strings.Join(lines, " | ")
}
